document.addEventListener("DOMContentLoaded", () => {
    // 1. Инициализация темы
    const themeToggle = document.getElementById('theme-toggle');
    const body = document.body;
    const savedTheme = localStorage.getItem('theme') || 'dark';
    body.setAttribute('data-theme', savedTheme);
    updateThemeIcon(savedTheme);

    themeToggle.addEventListener('click', () => {
        const currentTheme = body.getAttribute('data-theme');
        const newTheme = currentTheme === 'dark' ? 'light' : 'dark';
        body.setAttribute('data-theme', newTheme);
        localStorage.setItem('theme', newTheme);
        updateThemeIcon(newTheme);
    });

    function updateThemeIcon(theme) {
        themeToggle.innerHTML = theme === 'dark' ? "<i class='bx bx-sun'></i>" : "<i class='bx bx-moon'></i>";
    }

    // 2. Логика кастомного выпадающего списка
    const customSelect = document.querySelector('.custom-select');
    const selectOptions = document.querySelector('.select-options');
    const selectedLangText = document.querySelector('.selected-lang');
    
    const langOrder = ['en', 'jp', 'ru', 'uk'];
    const savedLang = localStorage.getItem('lang') || 'en';
    
    updateSelectUI(savedLang);
    applyLanguage(savedLang);

    customSelect.addEventListener('click', (e) => {
        e.stopPropagation();
        selectOptions.classList.toggle('active');
        document.querySelector('.arrow').style.transform = selectOptions.classList.contains('active') ? 'rotate(180deg)' : 'rotate(0)';
    });

    document.addEventListener('click', () => {
        selectOptions.classList.remove('active');
        document.querySelector('.arrow').style.transform = 'rotate(0)';
    });

    document.querySelectorAll('.select-options li').forEach(item => {
        item.addEventListener('click', (e) => {
            const selectedValue = e.target.getAttribute('data-value');
            localStorage.setItem('lang', selectedValue);
            updateSelectUI(selectedValue);
            applyLanguage(selectedValue);
        });
    });

    function updateSelectUI(langValue) {
        const textMap = { 'en': 'EN', 'jp': 'JP', 'ru': 'RU', 'uk': 'UK' };
        selectedLangText.innerHTML = `<i class='bx bx-globe'></i> ${textMap[langValue]}`;
    }

    function applyLanguage(lang) {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (translations[lang] && translations[lang][key]) {
                el.innerText = translations[lang][key];
            }
        });
    }

    // 3. Ленивая загрузка аватарок
    const lazyImages = document.querySelectorAll('.lazy-avatar');
    const imageObserver = new IntersectionObserver((entries, observer) => {
        entries.forEach(entry => {
            if (entry.isIntersecting) {
                const img = entry.target;
                const src = img.getAttribute('data-src');
                setTimeout(() => {
                    img.src = src;
                    img.onload = () => img.classList.add('loaded');
                }, 2000);
                observer.unobserve(img);
            }
        });
    });

    lazyImages.forEach(img => imageObserver.observe(img));
});